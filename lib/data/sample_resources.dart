CommunityResource _resource(
  String id,
  String name,
  ResourceCategory category,
  String description,
  String streetAddress,
  String city,
  String zipCode,
  String phone,
  String hours,
  bool isOpenNow,
  bool isWheelchairAccessible,
  String eligibility,
  String accessibility,
) {
  return CommunityResource(
    id: id,
    name: name,
    category: category,
    description: description,
    streetAddress: streetAddress,
    city: city,
    state: 'OR',
    zipCode: zipCode,
    phoneNumber: phone,
    website: Uri.parse('https://$id.example.org'),
    hours: hours,
    isOpenNow: isOpenNow,
    isWheelchairAccessible: isWheelchairAccessible,
    eligibilitySummary: eligibility,
    documentsToBring: const [
      'Photo ID if available',
      'Any relevant application paperwork',
    ],
    servicesOffered: _servicesFor(category),
    languagesSupported: const ['English', 'Spanish by appointment'],
    accessibilityInformation: accessibility,
    lastVerified: DateTime(2026, 9, 15),
  );
}

List<String> _servicesFor(ResourceCategory category) {
  return switch (category.id) {
    'food' => const ['Grocery pickup', 'Prepared meals', 'Nutrition referrals'],
    'housing' => const [
      'Housing navigation',
      'Application assistance',
      'Shelter referrals',
    ],
    'healthcare' => const [
      'Wellness screening',
      'Health education',
      'Care referrals',
    ],
    'family-support' => const [
      'Family resource navigation',
      'Parent support groups',
      'Childcare referrals',
    ],
    'employment' => const [
      'Resume support',
      'Job-search coaching',
      'Computer access',
    ],
    'transportation' => const [
      'Trip planning',
      'Fare assistance screening',
      'Ride referrals',
    ],
    _ => const ['Community resource navigation'],
  };
}
